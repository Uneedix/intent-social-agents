#!/usr/bin/env node
// Generates lib/emoji-data.ts from emojibase-data (Unicode CLDR/emoji-test based).
// Not a runtime dependency. Usage (install the package in a temp folder outside the repo):
//   mkdir /tmp/emoji-gen && cd /tmp/emoji-gen && npm pack emojibase-data@18 && tar xzf emojibase-data-*.tgz
//   node scripts/generate-emoji-data.mjs /tmp/emoji-gen/package/en/data.json
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const source = process.argv[2];
if (!source) { console.error('Usage: node scripts/generate-emoji-data.mjs <emojibase en/data.json>'); process.exit(1); }
const data = JSON.parse(readFileSync(source, 'utf8'));
const pkg = (() => { try { return JSON.parse(readFileSync(new URL('../package.json', `file://${source}`), 'utf8')); } catch { return {}; } })();

// emojibase groups -> Telegram-like categories (component group 2 is skipped).
const GROUP_MAP = { 0: 'people', 1: 'people', 3: 'nature', 4: 'food', 6: 'activity', 5: 'travel', 7: 'objects', 8: 'symbols', 9: 'flags' };
const ORDER = ['people', 'nature', 'food', 'activity', 'travel', 'objects', 'symbols', 'flags'];
const out = Object.fromEntries(ORDER.map(k => [k, []]));
const clean = s => s.replace(/[|\n\\`$]/g, ' ').replace(/\s+/g, ' ').trim();

let count = 0;
for (const item of data.sort((a, b) => (a.order ?? 1e9) - (b.order ?? 1e9))) {
  const cat = GROUP_MAP[item.group];
  if (!cat || item.type === undefined) continue;
  const name = clean(item.label);
  const nameWords = new Set(name.toLowerCase().split(/[\s:,]+/));
  const tags = [...new Set((item.tags || []).map(t => clean(t.toLowerCase())))].filter(t => t && !nameWords.has(t));
  let tones = '';
  if (item.skins) {
    // Only the five uniform tones (tone is a number, not a mixed array).
    const uniform = [1, 2, 3, 4, 5].map(t => item.skins.find(s => s.tone === t)?.emoji);
    if (uniform.every(Boolean)) tones = uniform.join(' ');
  }
  out[cat].push([item.emoji, name, tags.join(' '), tones].join('|').replace(/\|+$/, ''));
  count++;
}

const body = ORDER.map(k => `  ${k}: ${JSON.stringify(out[k].join('\n'))},`).join('\n');
const file = `// GENERATED by scripts/generate-emoji-data.mjs from emojibase-data${pkg.version ? `@${pkg.version}` : ''} (MIT, Unicode CLDR/emoji-test).
// Do not edit by hand. Line format: emoji|english name|keywords|5 skin-tone variants (space separated, optional).
// ${count} fully-qualified emoji. Loaded lazily via dynamic import from lib/emoji.ts.
export const EMOJI_COUNT = ${count};
export const EMOJI_RAW: Record<'${ORDER.join("' | '")}', string> = {
${body}
};
`;
const target = fileURLToPath(new URL('../lib/emoji-data.ts', import.meta.url));
writeFileSync(target, file);
console.log(`Wrote ${target}: ${count} emoji, ${Buffer.byteLength(file)} bytes`);
